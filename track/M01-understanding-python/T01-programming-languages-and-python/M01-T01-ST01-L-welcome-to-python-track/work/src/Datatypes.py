#int
a = 10
print(type(a), a) #<class 'int'> 10

#float
b = 3.14
print(type(b), b)# <class 'float'> 3.14

#bool
c = True
print(type(c), c) #<class 'bool'> True

#str
d = "Hello"
print(type(d), d) # <class 'str'> Hello

#list
e = [1, 2, 3]
print(type(e), e) # <class 'list'> [1, 2, 3]

#tuple
f = (1, 2, 3)
print(type(f), f) # <class 'tuple'> (1, 2, 3)

#dict
g = {1: "Hello", 2: "World"}
print(type(g) , g) #<class 'dict'> {1: 'Hello', 2: 'World'}

#set
h = {1,2,3,4,5}
print(type(h) , h) #<class 'set'> {1, 2, 3, 4, 5}

#complex
i = 1 +2j
print(type(i) , i)  #<class 'complex'> (1+2j)

#none
is_valid = None
print(type(is_valid), is_valid)#<class 'NoneType'> None

